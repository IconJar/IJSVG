void IJSVGExporterPathCaller(void* info, const CGPathElement* pathElement)
{
    IJSVGCGPathHandler handler = (__bridge IJSVGCGPathHandler)info;
    handler(pathElement);
};

void IJSVGEnumerateCGPathElements(CGPathRef path, IJSVGPathElementEnumerationBlock enumBlock)
{
    __block CGPoint currentPoint = CGPointZero;
    IJSVGCGPathHandler callback = ^(const CGPathElement* _Nonnull element) {
        switch (element->type) {
            case kCGPathElementMoveToPoint: {
                enumBlock(element, currentPoint);
                currentPoint = element->points[0];
                break;
            }
            case kCGPathElementAddLineToPoint: {
                enumBlock(element, currentPoint);
                currentPoint = element->points[0];
                break;
            }
            case kCGPathElementAddCurveToPoint: {
                enumBlock(element, currentPoint);
                currentPoint = element->points[2];
                break;
            }
            case kCGPathElementAddQuadCurveToPoint: {
                enumBlock(element, currentPoint);
                currentPoint = element->points[1];
                break;
            }
            case kCGPathElementCloseSubpath: {
                enumBlock(element, currentPoint);
                break;
            }
        }
    };
    CGPathApplyWithBlock(path, callback);
};

static double IJSVGExporterAttributeSortIndex(const char* name, NSUInteger fallback)
{
    static const struct {
        const char* name;
        size_t length;
    } order[] = {
        { "id", 2 }, { "width", 5 }, { "height", 6 }, { "x", 1 }, { "x1", 2 }, { "x2", 2 },
        { "y", 1 }, { "y1", 2 }, { "y2", 2 }, { "cx", 2 }, { "cy", 2 }, { "r", 1 },
        { "fill", 4 }, { "stroke", 6 }, { "marker", 6 }, { "d", 1 }, { "points", 6 },
        { "transform", 9 }, { "gradientTransform", 17 }, { "xlink:href", 10 }
    };
    for (NSUInteger index = 0; index < sizeof(order) / sizeof(*order); index++) {
        size_t length = order[index].length;
        if (strncmp(name, order[index].name, length) != 0) {
            continue;
        }
        if (name[length] == 0) {
            return index;
        }
        if (name[length] == '-') {
            return index + .5;
        }
    }
    return fallback;
}

- (void)sortAttributesOnElement:(IJSVGExportElement*)element
{
    IJSVGExportSortAttributes(element, IJSVGExporterAttributeSortIndex);
}

#pragma mark Delegate calling methods

- (NSString*)identifierForElement:(IJSVGExportElement* _Nullable)element
{
    NSString* identifier = nil;
    if (_respondsTo.identifierForElement == 1) {
        __weak id weakSelf = self;
        NSString* (^block)(void) = ^NSString*(void) {
            return [weakSelf generateID];
        };
        IJSVGNodeType type = IJSVGNodeTypeForString(element.localName, element.kind);
        identifier = [_delegate svgExporter:self identifierForElement:element type:type defaultID:block];
        if (identifier != nil) {
            return identifier;
        }
    }
    return [self generateID];
}

- (NSString*)colorStringForColor:(CGColorRef)color flag:(IJSVGColorUsageTraits)flag options:(IJSVGColorStringOptions)options
{
    NSString* colorString = nil;
    if (_respondsTo.stringForColor == 1) {
        color = [IJSVGColor computeColorSpace:color];
        colorString = [_delegate svgExporter:self stringForColor:color flags:flag options:options];
        if (colorString != nil) {
            return colorString;
        }
    }
    return [IJSVGColor colorStringFromColor:color options:options];
}

