- (void)_convertUseElements
{
    @autoreleasepool {
        NSArray<NSArray<IJSVGExportElement*>*>* groups = IJSVGExportDuplicatePaths(_dom);
        NSMutableArray<IJSVGExportElement*>* definitions = [[NSMutableArray alloc] initWithCapacity:groups.count];
        for (NSArray<IJSVGExportElement*>* group in groups) {
            NSString* data = [group.firstObject attributeForName:IJSVGAttributeD].stringValue;
            [definitions addObject:[self defPathElementForPathData:data]];
        }
        NSUInteger index = 0;
        for (NSArray<IJSVGExportElement*>* group in groups) {
            NSString* pathId = [definitions[index++] attributeForName:IJSVGAttributeID].stringValue;
            NSString* reference = IJSVGHash(pathId);
            for (IJSVGExportElement* element in group) {
                IJSVGExportElement* use = [[IJSVGExportElement alloc] initWithName:@"use"];
                [use setAttributeWithName:IJSVGAttributeXLink stringValue:reference];
                [self applyXLinkToRootElement];
                for (IJSVGExportNode* attribute in element.attributes) {
                    if ([attribute.name isEqualToString:IJSVGAttributeD]) {
                        continue;
                    }
                    [element removeAttributeForName:attribute.name];
                    [use addAttribute:attribute];
                }
                [element replaceWithNode:use];
            }
        }
        IJSVGExportElement* def = [self defElement];
        for (IJSVGExportElement* definition in definitions) {
            [def addChild:definition];
        }
    }
}

