/// Returns the serialized SVG as UTF8 text.
- (NSString*)SVGString
{
    return [[NSString alloc] initWithData:self.SVGData encoding:NSUTF8StringEncoding];
}

/// Passes declaration preferences directly to the XML serializer.
- (NSData*)SVGData
{
    BOOL includeXMLDeclaration = !IJSVGExporterHasOption(_options, IJSVGExporterOptionRemoveXMLDeclaration);
    return [[self _dom] XMLDataWithPrettyPrinting:[self prettyPrintXML] includeXMLDeclaration:includeXMLDeclaration];
}

- (IJSVG*)SVG:(NSError**)error
